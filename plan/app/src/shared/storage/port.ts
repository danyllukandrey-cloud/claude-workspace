// ЗАГЛУШКА. Порт сховища — опис "ЩО картці потрібно", без "ЯК це зроблено".
//
// Це інтерфейс: перелік дій, які картка має право попросити у сховища.
// Хто саме виконує ці дії — localStorage сьогодні чи сервер завтра — тут не вказано
// і не має значення.
//
// Правило залежностей (ADR-0004): domain картки має право імпортувати ЦЕЙ файл,
// але ніколи не local.ts. Підстановку реалізації робить app/main.tsx.
//
// Навіщо: коли з'явиться бекенд, поруч ляже http.ts, і жодну картку
// переписувати не доведеться (продовження ADR-0003).

/** Ключ-значення сховище. Форма інтерфейсу — чернетка, уточниться при реалізації. */
export interface StoragePort {
  read<T>(key: string): T | null;
  write<T>(key: string, value: T): void;
  remove(key: string): void;
}

/** Версія формату збережених даних. Потрібна для майбутньої міграції старих даних. */
export const SCHEMA_VERSION_KEY = 'schemaVersion';
