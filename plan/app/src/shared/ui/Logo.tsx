// Логотип ПЛАН (D-120) -- кубик Рубика, без напису. Третій захід (перший --
// "шість моніторів" зі скетчу -- невпізнавана клавіатура; другий -- кубик,
// який тримають руки -- геометричні "рукавички" виглядали дешево, органічна
// (bezier) спроба вийшла ще гірше -- Андрій обрав "лого без рук, лише
// кубик"). Кубик Рубика -- образ, який лишився: впорядковуєш розкидані
// шматки свого життя в одну картину.
//
// Перевірено локальним растеризатором (@resvg/resvg-js, сесія 2026-09-13) --
// не здогад "на око": ізометрична сітка порахована формулами нижче (не
// скопійована з ока), тому три видимі грані по 3х3 клітинки сходяться точно
// в спільних вершинах без "розповзання" ліній.
//
// Кольори кожної клітинки -- ЛИШЕ фірмова палітра D-120 (accent/good/warn/
// bad/surface-solid), не довільні кольори "як у справжнього кубика" --
// впізнається як кубик Рубика за формою й розбивкою на клітинки, а не за
// тим, що кольори збігаються з оригіналом.

