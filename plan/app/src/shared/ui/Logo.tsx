function Face({ cells }: { cells: Array<[string, CellColor]> }): JSX.Element {
  return (
    <>
      {cells.map(([points, color]) => (
        <polygon key={points} points={points} className={`${FILL_CLASS[color]} stroke-ink/40`} strokeWidth={1.2} strokeLinejoin="round" />
      ))}
    </>
  );
}

