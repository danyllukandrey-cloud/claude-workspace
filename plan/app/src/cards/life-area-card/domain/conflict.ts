export interface RawEntryWithTiming {
  recordedAt: number;
}

/**
 * D-119 (docs/DECISIONS.md): AC-06 раніше розрізняла "різні пристрої" через
 * `sourceDeviceId` -- єдине джерело РЕАЛЬНОГО device id було в тимчасовій
 * кнопці "+" на картці (D-110, main.tsx). Коли кнопку прибрали, єдиний
 * шлях запису лишився через `agent`'s confirm.ts, який завжди пише
 * `sourceDeviceId: null` (openapi.yaml не приймає це поле від клієнта --
 * рев'ю 2026-09-12 навмисне рішення не довіряти клієнтським значенням) --
 * жодного реального сигналу "інший пристрій" більше немає НІДЕ в системі
 * (agent не має поняття сесії розмови, лише userId).
 *
 * Тому AC-06 звужено: конфлікт -- це просто "два (не rejected) записи
 * ОДНОГО блоку близько за часом", незалежно від пристрою. Свідомо ширше за
 * попередню поведінку -- ціна: легітимний швидкий повторний запис теж
 * зрідка потрапить у "очікує перевірки" -- прийнятно, бо завжди
 * відновлювано (existing onFlagEntry-потік) і узгоджено з уже задекларованим
 * принципом картки "конфліктні близькі за часом записи ніколи не рахуються
 * мовчки" (spec.md §3).
 *
 * Це НЕ повторення бага B7 (review-2026-09-07.md, виправлено того ж дня
 * коміт c8c89c8): B7 був НЕПОМІЧЕНИМ дефектом першої версії (жоден клієнт
 * ще не слав device id, тож "невідомий -> можливо інший" ламало звичайний
 * односеансовий запис непередбачено). Тут -- свідомо ухвалене рішення після
 * того, як реального device-сигналу вже гарантовано ніде нема.
 */
export function detectConflict(newEntry: RawEntryWithTiming, existingEntries: RawEntryWithTiming[], windowMs: number): boolean {
  return existingEntries.some((existing) => Math.abs(newEntry.recordedAt - existing.recordedAt) <= windowMs);
}
